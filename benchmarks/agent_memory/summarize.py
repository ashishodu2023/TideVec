"""Average results/longmemeval_ku_*.json over models into results/summary.md."""

import json
from pathlib import Path

HERE = Path(__file__).parent
METRICS = ["current@1", "current@5", "stale@1", "stale_in_top5", "stale_first", "mrr"]


def main():
    runs = [json.loads(p.read_text()) for p in sorted((HERE / "results").glob("longmemeval_ku_*.json"))]
    names = list(runs[0]["strategies"])
    lines = ["# LongMemEval knowledge-update: results", "",
             f"Generated by `summarize.py`. {runs[0]['n_questions']} questions, k = {runs[0]['k']}. "
             "Each cell is the mean over the models; `[min-max]` is the per-model range.", "",
             "Models: " + ", ".join(r["model"] for r in runs), "",
             "| Strategy | " + " | ".join(METRICS) + " |",
             "|---|" + "---:|" * len(METRICS)]
    for name in names:
        rows = [r["strategies"].get(name, {}) for r in runs]
        if any("error" in x or not x for x in rows):
            lines.append(f"| {name} | " + " | ".join("n/a" for _ in METRICS) + " |")
            continue
        cells = []
        for m in METRICS:
            v = [x[m] for x in rows]
            cells.append(f"{sum(v) / len(v):.3f} [{min(v):.2f}-{max(v):.2f}]")
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    lines += ["", "## Per model", ""]
    for r in runs:
        lines += [f"### {r['model']}", "", "| Strategy | " + " | ".join(METRICS) + " |",
                  "|---|" + "---:|" * len(METRICS)]
        for name, x in r["strategies"].items():
            if "error" in x:
                lines.append(f"| {name} | error: {x['error']} |")
            else:
                lines.append(f"| {name} | " + " | ".join(f"{x[m]:.3f}" for m in METRICS) + " |")
        lines.append("")
    out = HERE / "results" / "summary.md"
    out.write_text("\n".join(lines) + "\n")
    print(out.read_text())


if __name__ == "__main__":
    main()
