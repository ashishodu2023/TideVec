"""
Summarise results/<corpus>_<model>.json into results/summary.md.

For each corpus and scenario: one table per query set (natural, and all
query sets pooled), metrics averaged over the embedding models, with the
per-model range of current@1 in brackets.

    python summarize.py
"""

import json
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).parent
RES = HERE / "results"
CORPORA = ["wiki", "policy", "docs"]
METRICS = ["current@1", "stale@1", "wrong@1", "stale_in_top5", "ndcg@10"]


def pooled(query_sets):
    """Average metrics over all query sets, weighted by query count."""
    out = defaultdict(lambda: defaultdict(float))
    total = sum(qs["n"] for qs in query_sets.values())
    for qs in query_sets.values():
        for s, m in qs["strategies"].items():
            for k in METRICS:
                out[s][k] += m[k] * qs["n"] / total
    return {"n": total, "strategies": out}


def main():
    lines = ["# Temporal benchmark v2: results", "",
             "Generated by `summarize.py`. Metrics are averaged over the embedding models; "
             "`[min-max]` is the per-model range of Current@1. Stale/top-5 = outdated versions of the "
             "right document in the top 5. nDCG@10 counts only the current version as relevant.", ""]
    for corpus in CORPORA:
        files = sorted(RES.glob(f"{corpus}_*.json"))
        if not files:
            continue
        runs = [json.loads(p.read_text()) for p in files]
        models = [r["model"] for r in runs]
        lines += [f"## {corpus}: {runs[0]['n_docs']} documents, {runs[0]['n_titles']} titles "
                  f"(models: {', '.join(models)})", ""]
        for scen in runs[0]["scenarios"]:
            sc0 = runs[0]["scenarios"][scen]
            lines += [f"### Scenario `{scen}` ({sc0['n_docs']} docs; current version median age "
                      f"{sc0['current_age_days']['median']:.0f} days, p90 "
                      f"{sc0['current_age_days']['p90']:.0f})", ""]
            for qname in ("natural", "all"):
                per_model = []
                for r in runs:
                    qsets = r["scenarios"][scen]["query_sets"]
                    if qname == "all":
                        per_model.append(pooled(qsets))
                    elif qname in qsets:
                        per_model.append(qsets[qname])
                if not per_model:
                    continue
                label = ("natural-language queries" if qname == "natural"
                         else "all query sets pooled (template question, oldest/newest first sentence, natural)")
                lines += [f"**{label}, n = {per_model[0]['n']} per model**", "",
                          "| Strategy | Current@1 | Stale@1 | Wrong doc@1 | Stale in top-5 | nDCG@10 |",
                          "|---|---:|---:|---:|---:|---:|"]
                for s in per_model[0]["strategies"]:
                    vals = {k: [pm["strategies"][s][k] for pm in per_model] for k in METRICS}
                    mean = {k: sum(v) / len(v) for k, v in vals.items()}
                    c = vals["current@1"]
                    lines.append(
                        f"| {s} | {mean['current@1'] * 100:.1f}% [{min(c) * 100:.0f}-{max(c) * 100:.0f}] | "
                        f"{mean['stale@1'] * 100:.1f}% | {mean['wrong@1'] * 100:.1f}% | "
                        f"{mean['stale_in_top5']:.2f} | {mean['ndcg@10']:.3f} |")
                lines.append("")
    (RES / "summary.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
