"""
Summarise results/*.json into results/summary.md and recall-vs-QPS plots.

    python report.py
"""

import json
from pathlib import Path

HERE = Path(__file__).parent
RES = HERE / "results"
ENGINES = ["tidevec", "hnswlib", "faiss"]
TARGETS = [0.80, 0.90, 0.95, 0.99]


def load(engine, ds, suffix=""):
    p = RES / f"{engine}_{ds}{suffix}.json"
    return json.loads(p.read_text()) if p.exists() and p.stat().st_size else None


def best_at(runs, target):
    ok = [r for r in runs if r["recall"] >= target]
    return max(ok, key=lambda r: r["qps"]) if ok else None


def main():
    datasets = sorted({p.stem.split("_", 1)[1] for p in RES.glob("tidevec_*.json")})
    lines = ["# ANN benchmark results", "",
             "Generated by `report.py` from `results/*.json`. M=16, ef_construction=200, k=10, "
             "single-threaded build and search unless noted.", ""]
    for ds in datasets:
        res = {e: load(e, ds) for e in ENGINES}
        if not any(res.values()):
            continue
        any_r = next(r for r in res.values() if r)
        lines += [f"## {ds} (n={any_r['n']:,}, d={any_r['d']}, {any_r['nq']:,} queries)", ""]
        lines += ["| Engine | Build, 1 thread (s) | Build, 16 threads (s) | Index RSS (MB) |",
                  "|---|---:|---:|---:|"]
        for e, r in res.items():
            if not r:
                continue
            b16 = load(e, ds, "_build16")
            lines.append(f"| {e} | {r['build_s']:.0f} | "
                         f"{b16['build_s']:.0f} | " if b16 else f"| {e} | {r['build_s']:.0f} | n/a (single-threaded insert) | ")
            lines[-1] += f"{r['index_rss_mb']:.0f} |"
        lines += ["", "Best single-thread QPS at a recall@10 target (p50 / p99 latency at that setting):", "",
                  "| Engine | " + " | ".join(f"recall ≥ {t}" for t in TARGETS) + " |",
                  "|---|" + "---:|" * len(TARGETS)]
        for e, r in res.items():
            if not r:
                continue
            cells = []
            for t in TARGETS:
                b = best_at(r["runs"], t)
                cells.append("not reached" if not b else
                             f"{b['qps']:,.0f} QPS (ef {b['ef_search']}; "
                             f"{b['p50_us'] / 1000:.2f} / {b['p99_us'] / 1000:.2f} ms)")
            lines.append(f"| {e} | " + " | ".join(cells) + " |")
        lines += ["", "Full ef_search sweep:", "",
                  "| Engine | ef | recall@10 | QPS (1 thread) | QPS (8 threads) | p50 ms | p99 ms |",
                  "|---|---:|---:|---:|---:|---:|---:|"]
        for e, r in res.items():
            if not r:
                continue
            for run in r["runs"]:
                lines.append(f"| {e} | {run['ef_search']} | {run['recall']:.4f} | {run['qps']:,.0f} | "
                             f"{run.get('qps_mt', 0):,.0f} | {run['p50_us'] / 1000:.3f} | "
                             f"{run['p99_us'] / 1000:.3f} |")
        lines.append("")
        try:
            import matplotlib
            matplotlib.use("Agg")
            import matplotlib.pyplot as plt
            fig, ax = plt.subplots(figsize=(6, 4))
            for e, r in res.items():
                if r:
                    ax.plot([x["recall"] for x in r["runs"]], [x["qps"] for x in r["runs"]],
                            marker="o", label=e)
            ax.set_yscale("log")
            ax.set_xlabel("recall@10")
            ax.set_ylabel("queries/s (1 thread)")
            ax.set_title(ds)
            ax.grid(True, which="both", alpha=0.3)
            ax.legend()
            fig.tight_layout()
            fig.savefig(RES / f"recall_qps_{ds}.png", dpi=120)
            lines += [f"![recall vs QPS](recall_qps_{ds}.png)", ""]
        except ImportError:
            pass
    (RES / "summary.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
